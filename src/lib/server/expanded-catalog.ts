export function seedExpandedCatalog(db: Database.Database, timestamp: number) {
  const exists = db.prepare('SELECT 1 FROM products WHERE name_de = ? COLLATE NOCASE AND active=1 LIMIT 1');
  const insert = db.prepare(
    "INSERT INTO products(id,category_id,name_de,name_en,source,active,created_at,updated_at) VALUES(?,?,?,?, 'catalog',1,?,?)"
  );
  for (const [category, de, en] of expandedCatalog) {
    if (!exists.get(de)) insert.run(randomUUID(),category,de,en,timestamp,timestamp);
  }
}
